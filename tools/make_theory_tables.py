#!/usr/bin/env python3
"""Emits firmware/liveplayer/src/gen/theory_tables.hpp from tools/theory_data.py (SPEC §9.24): the progression,
voicing, rhythm and Markov tables of the on-device THEORY SET GENERATOR as constexpr arrays (flash, ~3 KB). The same
Python tables drive tools/make_clips.py, so the card's generated clips and the device share one source of truth.

Usage:
  python3 -I tools/make_theory_tables.py            # (re)writes the header next to gen/variants.cpp
  python3 -I tools/make_theory_tables.py --check    # exit 1 when the header on disk is stale (tests/run_theory.sh)
  python3 -I tools/make_theory_tables.py --out FILE

Encodings (decoded by gen/variants.cpp, asserted by tests/test_theory.cpp):
  chord code      degree | alteration << 3 (theory_data.CHORD_TOKENS)
  Prog            {n, beatsPerChord, chords[8]} + a parallel weight array
  rhythm step     2 bits: 0 rest, 1 onset, 2 accent, 3 hold; 16 steps = one uint32_t (step k at bits 2k..2k+1)
  bass step       4 bits (theory_data.BASS_CODES); 16 steps = one uint64_t (step k at bits 4k..4k+3)
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))     # -I keeps the script dir off sys.path
import theory_data as td  # noqa: E402

DEFAULT_OUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "liveplayer", "src", "gen", "theory_tables.hpp"))
MIN_PROGRESSIONS = 100
MIN_RHYTHMS = 100


def pack_rhythm(mask):
    if len(mask) != 16:
        raise ValueError("rhythm template %r is not 16 steps" % mask)
    v = 0
    for k, c in enumerate(mask):
        v |= td.RHYTHM_CODES[c] << (2 * k)
    return v


def pack_bass(mask):
    if len(mask) != 16:
        raise ValueError("bass template %r is not 16 steps" % mask)
    v = 0
    for k, c in enumerate(mask):
        v |= td.BASS_CODES[c] << (4 * k)
    return v


def rows(items, per_line, fmt):
    out = []
    for i in range(0, len(items), per_line):
        out.append("  " + ", ".join(fmt(x) for x in items[i:i + per_line]) + ",")
    return "\n".join(out)


def build():
    progs = td.theory_progressions()
    seen = set()
    for toks, beats, w in progs:
        key = (tuple(toks), beats)
        if key in seen:
            raise ValueError("duplicate progression %r x %d beats" % (" ".join(toks), beats))
        seen.add(key)
        if not 1 <= w <= 255:
            raise ValueError("weight out of range in %r" % " ".join(toks))
    if len(progs) < MIN_PROGRESSIONS:
        raise ValueError("only %d progressions (>= %d required)" % (len(progs), MIN_PROGRESSIONS))
    chord_r = td.theory_chord_rhythms()
    bass_r = list(td.BASS_RHYTHMS)
    lead_r = td.theory_lead_rhythms()
    n_rhythms = len(chord_r) + len(bass_r) + len(lead_r)
    if n_rhythms < MIN_RHYTHMS:
        raise ValueError("only %d rhythm templates (>= %d required)" % (n_rhythms, MIN_RHYTHMS))
    for mask, w, name in chord_r + lead_r:
        if mask[0] not in "xX":
            raise ValueError("template %s (%r) must start with an onset (crop variants)" % (name, mask))
    for mask, w, name in bass_r:
        if mask[0] not in "rRoOfFt":
            raise ValueError("bass template %s (%r) must start with a note" % (name, mask))
    for name, stack, style, w in td.VOICINGS:
        if not 2 <= len(stack) <= 4 or style not in ("close", "open"):
            raise ValueError("voicing %s" % name)
    for row in td.LEAD_MARKOV:
        if len(row) != 7 or sum(row) == 0:
            raise ValueError("LEAD_MARKOV row")

    L = []
    L.append("// GENERATED by tools/make_theory_tables.py from tools/theory_data.py — do not edit (SPEC §9.24).")
    L.append("// Flash tables of the on-device theory set generator: %d minor-key progressions, %d voicing templates, %d chord +"
             % (len(progs), len(td.VOICINGS), len(chord_r)))
    L.append("// %d bass + %d lead rhythm templates (%d), the lead's scale-degree Markov table. constexpr: .rodata, no RAM."
             % (len(bass_r), len(lead_r), n_rhythms))
    L.append("#pragma once")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("namespace lp {")
    L.append("namespace theory {")
    L.append("")
    L.append("// Chord code = degree (0..6, natural minor i ii III iv v VI VII) | alteration << 3.")
    L.append("enum Alt : uint8_t { AltNone = %d, AltMajor = %d, AltSus4 = %d, AltSus2 = %d, AltRaisedRoot = %d };"
             % (td.ALT_NONE, td.ALT_MAJOR, td.ALT_SUS4, td.ALT_SUS2, td.ALT_RAISED_ROOT))
    L.append("constexpr int kMaxChords = 8;")
    L.append("struct Prog { uint8_t n; uint8_t beatsPerChord; uint8_t chords[kMaxChords]; };")
    L.append("constexpr int kProgCount = %d;" % len(progs))
    L.append("constexpr Prog kProgs[kProgCount] = {")
    for toks, beats, w in progs:
        codes = [td.chord_code(t) for t in toks] + [0] * (8 - len(toks))
        L.append("  {%d, %d, {%s}},   // %s" % (len(toks), beats, ", ".join("%d" % c for c in codes), " ".join(toks)))
    L.append("};")
    L.append("constexpr uint8_t kProgW[kProgCount] = {")
    L.append(rows([w for _, _, w in progs], 24, lambda x: "%d" % x))
    L.append("};")
    L.append("")
    L.append("// Voicing templates: n scale-degree offsets above the chord degree; open = drop 2 (the second-highest voice an octave down).")
    L.append("struct Voicing { uint8_t n; uint8_t open; uint8_t stack[4]; };")
    L.append("constexpr int kVoicingCount = %d;" % len(td.VOICINGS))
    L.append("constexpr Voicing kVoicings[kVoicingCount] = {")
    for name, stack, style, w in td.VOICINGS:
        st = list(stack) + [0] * (4 - len(stack))
        L.append("  {%d, %d, {%s}},   // %s" % (len(stack), 1 if style == "open" else 0, ", ".join("%d" % x for x in st), name))
    L.append("};")
    L.append("constexpr uint8_t kVoicingW[kVoicingCount] = {%s};" % ", ".join("%d" % w for _, _, _, w in td.VOICINGS))
    L.append("")
    L.append("// Rhythm templates: 16 steps of a bar, 2 bits per step (step k at bits 2k..2k+1): 0 rest, 1 onset, 2 accent, 3 hold.")
    L.append("enum Step : uint8_t { StepRest = 0, StepOn = 1, StepAccent = 2, StepHold = 3 };")
    L.append("constexpr int kChordRhythmCount = %d;" % len(chord_r))
    L.append("constexpr uint32_t kChordRhythms[kChordRhythmCount] = {")
    for mask, w, name in chord_r:
        L.append("  0x%08Xu,   // %s %s" % (pack_rhythm(mask), mask, name))
    L.append("};")
    L.append("constexpr uint8_t kChordRhythmW[kChordRhythmCount] = {")
    L.append(rows([w for _, w, _ in chord_r], 24, lambda x: "%d" % x))
    L.append("};")
    L.append("constexpr int kLeadRhythmCount = %d;" % len(lead_r))
    L.append("constexpr uint32_t kLeadRhythms[kLeadRhythmCount] = {")
    for mask, w, name in lead_r:
        L.append("  0x%08Xu,   // %s %s" % (pack_rhythm(mask), mask, name))
    L.append("};")
    L.append("constexpr uint8_t kLeadRhythmW[kLeadRhythmCount] = {")
    L.append(rows([w for _, w, _ in lead_r], 24, lambda x: "%d" % x))
    L.append("};")
    L.append("")
    L.append("// Bass templates: 16 steps, 4 bits per step (step k at bits 4k..4k+3).")
    codes = sorted(td.BASS_CODES.items(), key=lambda kv: kv[1])
    names = {".": "Rest", "r": "Root", "R": "RootAccent", "o": "Oct", "O": "OctAccent", "f": "Fifth", "F": "FifthBelow", "a": "Approach", "-": "Hold", "t": "Third"}
    L.append("enum BassStep : uint8_t { %s };" % ", ".join("Bass%s = %d" % (names[c], v) for c, v in codes))
    L.append("constexpr int kBassTplCount = %d;" % len(bass_r))
    L.append("constexpr uint64_t kBassTpls[kBassTplCount] = {")
    for mask, w, name in bass_r:
        L.append("  0x%016Xull,   // %s %s" % (pack_bass(mask), mask, name))
    L.append("};")
    L.append("constexpr uint8_t kBassTplW[kBassTplCount] = {")
    L.append(rows([w for _, w, _ in bass_r], 24, lambda x: "%d" % x))
    L.append("};")
    L.append("")
    L.append("// Lead walk: row = the current scale degree, column = the next degree's weight; the motif's first degree; variation ops.")
    L.append("constexpr uint8_t kLeadMarkov[7][7] = {")
    for row in td.LEAD_MARKOV:
        L.append("  {%s}," % ", ".join("%d" % x for x in row))
    L.append("};")
    L.append("constexpr uint8_t kLeadStart[7] = {%s};" % ", ".join("%d" % x for x in td.LEAD_START))
    L.append("enum LeadVar : uint8_t { %s };" % ", ".join("Var%s = %d" % (n.capitalize(), i) for i, (n, _) in enumerate(td.LEAD_VARIATIONS)))
    L.append("constexpr int kLeadVarCount = %d;" % len(td.LEAD_VARIATIONS))
    L.append("constexpr uint8_t kLeadVarW[kLeadVarCount] = {%s};" % ", ".join("%d" % w for _, w in td.LEAD_VARIATIONS))
    L.append("")
    L.append("constexpr int kRhythmTotal = kChordRhythmCount + kBassTplCount + kLeadRhythmCount;")
    L.append("static_assert(kProgCount >= %d && kRhythmTotal >= %d, \"SPEC 9.24: >= 100 progressions and >= 100 rhythm templates\");" % (MIN_PROGRESSIONS, MIN_RHYTHMS))
    L.append("")
    L.append("} // namespace theory")
    L.append("} // namespace lp")
    L.append("")
    return "\n".join(L), dict(progressions=len(progs), voicings=len(td.VOICINGS), chord=len(chord_r), bass=len(bass_r), lead=len(lead_r))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="compare with the file on disk instead of writing")
    args = ap.parse_args(argv)
    text, stats = build()
    if args.check:
        try:
            on_disk = open(args.out).read()
        except OSError:
            print("theory_tables.hpp missing: %s" % args.out)
            return 1
        if on_disk != text:
            print("theory_tables.hpp is stale: rerun python3 -I tools/make_theory_tables.py")
            return 1
        print("theory_tables.hpp up to date (%s)" % ", ".join("%s %d" % kv for kv in stats.items()))
        return 0
    with open(args.out, "w") as f:
        f.write(text)
    print("wrote %s: %s" % (args.out, ", ".join("%s %d" % kv for kv in stats.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
